//! The CME Globex session, written out independently of perps-core's
//! `session` module: US Eastern time comes from a table of DST transitions
//! taken from the IANA America/New_York zone (not computed from calendar
//! rules), and the hours are the exchange's published ones: Sunday 18:00 to
//! Friday 17:00 ET, with a daily break from 17:00 to 18:00 ET.
//!
//! The simulation gates agents and computes the weekend margins with this, and
//! checks every tick that the engine's schedule agrees (invariant
//! 10_session_model). A DST or schedule bug in the engine then shows up as a
//! disagreement or an unpredicted MarketClosed, instead of being shared.

const HOUR: i64 = 3_600;
const DAY: i64 = 86_400;

/// `(EDT starts, EDT ends)` as Unix seconds, one row per year from 2020, from
/// Python's zoneinfo (IANA tzdata) for America/New_York.
const EDT: [(i64, i64); 22] = [
    (1583650800, 1604210400), // 2020
    (1615705200, 1636264800), // 2021
    (1647154800, 1667714400), // 2022
    (1678604400, 1699164000), // 2023
    (1710054000, 1730613600), // 2024
    (1741503600, 1762063200), // 2025
    (1772953200, 1793512800), // 2026
    (1805007600, 1825567200), // 2027
    (1836457200, 1857016800), // 2028
    (1867906800, 1888466400), // 2029
    (1899356400, 1919916000), // 2030
    (1930806000, 1951365600), // 2031
    (1962860400, 1983420000), // 2032
    (1994310000, 2014869600), // 2033
    (2025759600, 2046319200), // 2034
    (2057209200, 2077768800), // 2035
    (2088658800, 2109218400), // 2036
    (2120108400, 2140668000), // 2037
    (2152162800, 2172722400), // 2038
    (2183612400, 2204172000), // 2039
    (2215062000, 2235621600), // 2040
    (2246511600, 2267071200), // 2041
];

/// 2020-01-01 and 2042-01-01 00:00 UTC: the table's range.
const TABLE_START: i64 = 1_577_836_800;
const TABLE_END: i64 = 2_272_147_200;

/// US Eastern UTC offset at `ts` (seconds; -4 h in EDT, -5 h in EST).
pub fn eastern_offset(ts: i64) -> i64 {
    assert!((TABLE_START..TABLE_END).contains(&ts), "time {} outside the DST table (2020-2041)", ts);
    if EDT.iter().any(|&(start, end)| (start..end).contains(&ts)) {
        -4 * HOUR
    } else {
        -5 * HOUR
    }
}

/// Eastern wall clock at `ts`: (weekday with 0 = Sunday, seconds since local midnight).
pub fn eastern(ts: i64) -> (i64, i64) {
    let local = ts + eastern_offset(ts);
    // 1970-01-01 was a Thursday
    ((local.div_euclid(DAY) + 4).rem_euclid(7), local.rem_euclid(DAY))
}

const OPEN: i64 = 18 * HOUR;
const CLOSE: i64 = 17 * HOUR;

/// Whether CME Globex is in session at `ts`.
pub fn is_open(ts: i64) -> bool {
    let (weekday, secs) = eastern(ts);
    match weekday {
        0 => secs >= OPEN,
        1..=4 => secs < CLOSE || secs >= OPEN,
        5 => secs < CLOSE,
        _ => false,
    }
}

/// The first Friday 17:00 ET strictly after `ts`, as Unix seconds.
pub fn next_weekly_close(ts: i64) -> i64 {
    let (weekday, secs) = eastern(ts);
    let mut days = (5 - weekday).rem_euclid(7);
    if days == 0 && secs >= CLOSE {
        days = 7;
    }
    // Local wall time of that close, then back to UTC at the close's own offset
    let local_close = ts + eastern_offset(ts) - secs + days * DAY + CLOSE;
    let guess = local_close - eastern_offset(ts);
    local_close - eastern_offset(guess)
}

/// Whether `ts` is in session and within `window` seconds of the weekly close.
pub fn in_pre_close_window(ts: i64, window: u32) -> bool {
    window > 0 && is_open(ts) && next_weekly_close(ts) - ts <= window as i64
}

/// The market's schedule as the model sees it: 0 = always open, 1 = CME Globex.
pub fn market_open(schedule: u8, ts: i64) -> bool {
    schedule == 0 || is_open(ts)
}

pub fn market_pre_close(schedule: u8, ts: i64, window: u32) -> bool {
    schedule != 0 && in_pre_close_window(ts, window)
}

#[cfg(test)]
mod tests {
    use super::*;

    // The engine's reference vectors, generated by scripts/gen-session-vectors.py
    // from the IANA zone (not from either implementation)
    include!("../../programs/perps-core/src/session_vectors.rs");

    #[test]
    fn matches_the_iana_reference_vectors() {
        for &(ts, open, until_close) in SESSION_VECTORS {
            assert_eq!(is_open(ts), open, "is_open at {}", ts);
            if open {
                assert_eq!(next_weekly_close(ts) - ts, until_close, "seconds to the weekly close at {}", ts);
            }
        }
        for &(ts, offset) in OFFSET_VECTORS {
            assert_eq!(eastern_offset(ts), offset, "offset at {}", ts);
        }
    }

    #[test]
    fn the_simulated_week() {
        // Wed 2026-11-11 12:00 ET (EST, UTC-5) is 17:00 UTC
        let wed_noon = 1_794_416_400;
        assert_eq!(eastern(wed_noon), (3, 12 * HOUR));
        assert!(is_open(wed_noon));
        // Daily break 17:00-18:00 ET
        assert!(is_open(wed_noon + 5 * HOUR - 1));
        assert!(!is_open(wed_noon + 5 * HOUR));
        assert!(!is_open(wed_noon + 6 * HOUR - 1));
        assert!(is_open(wed_noon + 6 * HOUR));
        // Fri 17:00 ET weekly close; the 2 h window before it
        let fri_close = 1_794_607_200;
        assert_eq!(next_weekly_close(wed_noon), fri_close);
        assert!(in_pre_close_window(fri_close - 7_200, 7_200));
        assert!(!in_pre_close_window(fri_close - 7_201, 7_200));
        assert!(!is_open(fri_close));
        // Sunday 18:00 ET reopen
        let sun_open = fri_close + 2 * DAY + HOUR;
        assert!(!is_open(sun_open - 1));
        assert!(is_open(sun_open));
    }

    #[test]
    fn agrees_with_the_engine_on_the_vectors() {
        use perps_core::session as engine;
        for &(ts, _, _) in SESSION_VECTORS {
            assert_eq!(is_open(ts), engine::is_open(engine::SCHEDULE_CME_GLOBEX, ts));
            assert_eq!(in_pre_close_window(ts, 7_200), engine::in_pre_close_window(engine::SCHEDULE_CME_GLOBEX, ts, 7_200));
        }
    }
}
